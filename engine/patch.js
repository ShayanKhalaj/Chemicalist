"use strict";

/**
 * Minimal, dependency-free text patching used for generator-owned files that
 * embed a *generated* block inside hand-written context:
 *
 *   // <chemicalist:block name="routes">
 *   ...generated content...
 *   // </chemicalist:block>
 *
 * Outside the block the file is preserved exactly; inside it is replaced.
 */

function blockMarkers(name) {
  return {
    start: '// <chemicalist:block name="' + name + '">',
    end: "// </chemicalist:block>",
  };
}

function renderBlock(name, body, indent = "") {
  const markers = blockMarkers(name);
  const indented = String(body)
    .replace(/\s+$/, "")
    .split("\n")
    .map((line) => (line.length ? indent + line : line))
    .join("\n");
  return markers.start + "\n" + indented + "\n" + indent + markers.end;
}

/**
 * Replaces the named block. If the block does not exist yet, inserts it:
 *  - after `anchor` (a line containing that text) when provided,
 *  - otherwise at the end of the file.
 */
function patchBlock(content, name, body, options = {}) {
  const markers = blockMarkers(name);
  const startIndex = content.indexOf(markers.start);
  const endIndex =
    startIndex >= 0
      ? content.indexOf(markers.end, startIndex + markers.start.length)
      : -1;

  if (startIndex >= 0 && endIndex > startIndex) {
    const lineStart = content.lastIndexOf("\n", startIndex - 1) + 1;
    const linePrefix = content.slice(lineStart, startIndex);
    const markerIndent = /^\s*$/.test(linePrefix) ? linePrefix : "";
    const rendered = renderBlock(name, body).replace(
      markers.end,
      markerIndent + markers.end,
    );
    return (
      content.slice(0, startIndex) +
      rendered +
      content.slice(endIndex + markers.end.length)
    );
  }

  if (options.anchor) {
    const anchorIndex = content.indexOf(options.anchor);
    if (anchorIndex >= 0) {
      const lineEnd = content.indexOf("\n", anchorIndex);
      const insertAt = lineEnd === -1 ? content.length : lineEnd + 1;
      return (
        content.slice(0, insertAt) +
        "\n" +
        renderBlock(name, body) +
        "\n" +
        content.slice(insertAt)
      );
    }
  }

  return content.replace(/\s*$/, "\n\n") + renderBlock(name, body) + "\n";
}

/** True when a file is generator-owned (has the generated marker). */
function isGeneratedFile(content) {
  return content
    .replace(/^\uFEFF/, "")
    .trimStart()
    .startsWith("// @generated by chemicalist-generator");
}

module.exports = { patchBlock, renderBlock, blockMarkers, isGeneratedFile };
