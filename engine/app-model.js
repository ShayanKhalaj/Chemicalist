"use strict";

/**
 * Combines one validated manifest with the application registry into a single
 * descriptor that every generator/template renders from.
 *
 * Paths are relative to the application root and are computed here once so
 * generated imports and file names can never disagree.
 */

const { pascal, camel, kebab } = require("./naming");

const GENERATED_MARKER = "// @generated by chemicalist-generator";

function studioRoot(manifest) {
  return ["src", "labs", manifest.labSlug, "studios", manifest.studioSlug].join(
    "/",
  );
}

function modelPaths(root, model) {
  const base = kebab(model.name);
  return {
    domain: root + "/domain/models/" + base + ".model",
    enums: root + "/domain/enums/studio-enums",
    dtoCreate: root + "/application/dtos/create-" + base + ".dto",
    dtoUpdate: root + "/application/dtos/update-" + base + ".dto",
    dtoQuery: root + "/application/dtos/" + base + "-query.dto",
    dto: root + "/application/dtos/" + base + ".dto",
    schema: root + "/application/validators/" + base + ".schemas",
    repositoryContract:
      root + "/application/contracts/" + base + ".repository.contract",
    repositoryToken: root + "/application/contracts/" + base + ".tokens",
    serviceContract:
      root + "/application/contracts/" + base + ".service.contract",
    mapper: root + "/application/mappers/" + base + ".mapper",
    useCases: root + "/application/use-cases/" + base + ".use-cases",
    persistenceModel: root + "/persistence/models/" + base + ".persistence",
    prismaMapper: root + "/persistence/mappers/" + base + ".prisma.mapper",
    repository:
      root + "/persistence/repositories/prisma-" + base + ".repository",
    controller: root + "/presentation/controllers/" + base + ".controller",
    events: root + "/application/events/" + base + ".events",
    serviceSpec: root + "/application/use-cases/" + base + ".use-cases.spec",
    spec: root + "/application/use-cases/" + base + ".use-cases.spec",
  };
}

module.exports = {
  GENERATED_MARKER,
  studioRoot,
  modelPaths,
  pascal,
  camel,
  kebab,
};
