"use strict";

/**
 * Application bootstrap and role files.
 *
 * - `main.ts`, `app.module.ts`, `platform/*.module.ts` and `src/manifest-registry.ts`
 *   are *generator-owned* and completely rewritten on every generation, but they
 *   read the studio list from {@link manifestRegistry} so a new studio never
 *   requires editing shared code.
 * - `scripts/apply-registry.ts` is an application-owned file: only its
 *   `<chemicalist:block>` sections are patched.
 */

function manifestRegistry(ctx) {
  // The registry lists every studio of the application, not only the studio of
  // the current run: app-wide files are generated once per application.
  const studios = (ctx.registeredStudios || ctx.studios)
    .map(
      (studio) =>
        "  {\n" +
        "    key: " +
        JSON.stringify(studio.key) +
        ",\n" +
        "    lab: " +
        JSON.stringify(studio.lab) +
        ",\n" +
        "    studio: " +
        JSON.stringify(studio.studio) +
        ",\n" +
        "    labSlug: " +
        JSON.stringify(studio.labSlug) +
        ",\n" +
        "    studioSlug: " +
        JSON.stringify(studio.studioSlug) +
        ",\n" +
        "    title: " +
        JSON.stringify(studio.title) +
        ",\n" +
        "  }",
    )
    .join(",\n");

  return `/**
 * Manifest registry: the single source of truth for which studios exist.
 *
 * Generated by chemicalist from the generation registry. Add a studio by
 * running the CLI again, not by editing this file.
 */
export interface StudioDescriptor {
  key: string;
  lab: string;
  studio: string;
  labSlug: string;
  studioSlug: string;
  title: string;
}

export const studios: StudioDescriptor[] = [
${studios}
];

export function findStudio(labSlug: string, studioSlug: string): StudioDescriptor | undefined {
  return studios.find((studio) => studio.labSlug === labSlug && studio.studioSlug === studioSlug);
}
`;
}

function appModule(ctx) {
  const studioImports = (ctx.registeredStudios || ctx.studios)
    .map((studio) => {
      const moduleFile =
        "./labs/" +
        studio.labSlug +
        "/studios/" +
        studio.studioSlug +
        "/" +
        studio.studioSlug +
        ".module";
      return "import { " + studio.moduleName + " } from '" + moduleFile + "';";
    })
    .join("\n");

  const platformImports = [
    "import { APP_FILTER, APP_PIPE } from '@nestjs/core';",
    "import { ZodValidationPipe } from 'nestjs-zod';",
    "import { PlatformModule } from './platform/platform.module';",
    "import { DatabaseModule } from './infrastructure/database/database.module';",
    "import { AllExceptionsFilter } from './shared/filters/all-exceptions.filter';",
    "import { ZodValidationExceptionFilter } from './shared/filters/zod-validation-exception.filter';",
    "import { HealthModule } from './platform/observability/health/health.module';",
  ];

  const imports = ["PlatformModule", "DatabaseModule"];
  const providers = [
    "{ provide: APP_PIPE, useClass: ZodValidationPipe }",
    "{ provide: APP_FILTER, useClass: ZodValidationExceptionFilter }",
    "{ provide: APP_FILTER, useClass: AllExceptionsFilter }",
  ];

  platformImports.push(
    "import { UnitOfWorkModule } from './infrastructure/database/unit-of-work.module';",
  );
  imports.push("UnitOfWorkModule");
  if (ctx.has("cache")) {
    platformImports.push(
      "import { CacheInfrastructureModule } from './infrastructure/cache/cache.module';",
    );
    imports.push("CacheInfrastructureModule");
  }
  if (ctx.has("messaging")) {
    platformImports.push(
      "import { MessagingInfrastructureModule } from './platform/communication/messaging/messaging.module';",
    );
    imports.push("MessagingInfrastructureModule");
  }
  if (ctx.has("outbox")) {
    platformImports.push(
      "import { OutboxModule } from './platform/communication/outbox/outbox.module';",
    );
    imports.push("OutboxModule");
  }
  if (ctx.has("inbox")) {
    platformImports.push(
      "import { InboxModule } from './platform/communication/inbox/inbox.module';",
    );
    imports.push("InboxModule");
  }
  if (ctx.has("saga")) {
    platformImports.push(
      "import { SagaModule } from './platform/communication/saga/saga.module';",
    );
    imports.push("SagaModule");
  }

  const studioModules = (ctx.registeredStudios || ctx.studios).map(
    (studio) => studio.moduleName,
  );

  return `import { Module } from '@nestjs/common';
${platformImports.join("\n")}
${studioImports}

/**
 * Root module of the Chemicalist modular monolith.
 *
 * Shared infrastructure is registered once here (global modules); every studio
 * module only contributes its own use cases, repositories and controllers.
 */
@Module({
  imports: [
${imports.map((item) => "    " + item + ",").join("\n")}
    HealthModule,
${studioModules.map((item) => "    " + item + ",").join("\n")}
  ],
  providers: [
${providers.map((item) => "    " + item + ",").join("\n")}
  ],
})
export class AppModule {}
`;
}

function main(ctx) {
  const versioning = ctx.app.hasVersioning
    ? `
    app.enableVersioning({
      type: VersioningType.URI,
      defaultVersion: process.env.API_VERSION ?? '${ctx.app.api.version}',
    });`
    : "";

  return `import 'reflect-metadata';
import { Logger,${ctx.app.hasVersioning ? ' VersioningType,' : ''} type INestApplication } from '@nestjs/common';
import { NestExpressApplication } from '@nestjs/platform-express';
import type { NextFunction, Request, Response } from 'express';
import { NestFactory } from '@nestjs/core';
import { ConfigService } from '@nestjs/config';
import { AppModule } from './app.module';
import { AuthService } from './platform/security/auth/auth.service';
import { RequestIdMiddleware } from './shared/middleware/request-id.middleware';
import { RequestContext, type RequestIdentity } from './shared/context/request-context';

/**
 * Application bootstrap.
 *
 * Order matters: environment -> HTTP scope middleware -> module graph ->
 * platform bootstrap (permissions, tenant, administrator, module registry).
 */
async function bootstrap(): Promise<void> {
  const app = await NestFactory.create<NestExpressApplication>(AppModule, {
    bufferLogs: false,
  });
  const config = app.get(ConfigService);

  app.setGlobalPrefix('${ctx.app.api.prefix}');${versioning}

  app.enableCors({
    origin: (config.get<string>('CORS_ORIGIN') ?? '${ctx.app.api.corsOrigin}').split(',').map((origin) => origin.trim()),
    credentials: true,
    allowedHeaders: ['Content-Type', 'Authorization', 'x-request-id', 'x-correlation-id'],
    exposedHeaders: ['x-request-id'],
  });

  // File uploads are submitted as base64 JSON; keep the limit explicit.
  app.useBodyParser('json', { limit: '10mb' });
  app.enableShutdownHooks();

  app.use(new RequestIdMiddleware().use.bind(new RequestIdMiddleware()));

  // Wrap each request in an AsyncLocalStorage scope so the identity/tenant
  // resolved by the guards is visible to use cases and repositories.
  app.use((req: Request, _res: Response, next: NextFunction) => {
    const identity: RequestIdentity = {
      userId: '',
      email: '',
      roles: [],
      tenantId: undefined,
      isPlatformAdmin: false,
      requestId: String(req.headers['x-request-id'] ?? ''),
    };
    RequestContext.run(identity, () => next());
  });

  // Request bodies are validated by ZodValidationPipe (nestjs-zod, registered in
  // AppModule); unknown keys are rejected by the strict object schemas.
  const auth = app.get(AuthService);
  await auth.bootstrap();

  const port = Number(config.get('PORT') ?? ${ctx.app.api.port});
  await app.listen(port);
  Logger.log('API listening on http://localhost:' + port + '${ctx.app.urlPrefix(false)}', 'Bootstrap');
}

export { bootstrap };

if (require.main === module) {
  void bootstrap();
}
`;
}

