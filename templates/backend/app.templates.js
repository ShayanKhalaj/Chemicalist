function applyRegistryScript(ctx) {
  const models = ctx.appManifests.flatMap((manifest) =>
    manifest.models.map((model) => ({ manifest, model })),
  );

  const entries = models
    .map(({ manifest, model }) => {
      const camel = model.name.charAt(0).toLowerCase() + model.name.slice(1);
      const delegate = require("../../engine/naming").camelPlural(model.name);
      return (
        "  {\n" +
        "    name: " +
        JSON.stringify(model.name) +
        ",\n" +
        "    lab: " +
        JSON.stringify(manifest.lab) +
        ",\n" +
        "    studio: " +
        JSON.stringify(manifest.studio) +
        ",\n" +
        "    apiPath: " +
        JSON.stringify(
          "/" +
            manifest.labSlug +
            "/" +
            manifest.studioSlug +
            "/" +
            require("../../engine/naming").kebabPlural(model.name),
        ) +
        ",\n" +
        "    delegate: (prisma) => prisma." +
        delegate +
        ",\n" +
        "    tenantScoped: " +
        (ctx.has("tenantScope") ? "true" : "false") +
        ",\n" +
        "    searchFields: " +
        JSON.stringify(model.searchFields) +
        ",\n" +
        "    label: " +
        JSON.stringify(model.label) +
        ",\n" +
        "    variable: " +
        JSON.stringify(camel) +
        ",\n" +
        "  }"
      );
    })
    .join(",\n");

  return `import { randomUUID } from 'node:crypto';
import { PrismaClient } from '@prisma/client';
import { hash } from 'bcryptjs';

/**
 * App-owned demo data script.
 *
 * Generator-owned sections are marked with chemicalist:block markers; the rest
 * of this file (your own scenarios, fixtures, extra setup) is preserved when the
 * generator runs again.
 */
const prisma = new PrismaClient();

interface ModelSpec {
  name: string;
  lab: string;
  studio: string;
  apiPath: string;
  delegate: (prisma: PrismaClient) => {
    count(args?: unknown): Promise<number>;
    create(args: unknown): Promise<unknown>;
  };
  tenantScoped: boolean;
  searchFields: string[];
  label: string;
  variable: string;
}

// <chemicalist:block name="models">
export const models: ModelSpec[] = [
${entries}
];
// </chemicalist:block>

async function ensureTenantUser(): Promise<string | undefined> {
  // <chemicalist:block name="tenant-user">
${
  ctx.has("tenantScope")
    ? `  const tenantId = randomUUID();
  await prisma.chemicalistUser.upsert({
    where: { email: 'demo@chemicalist.local' },
    update: {},
    create: {
      email: 'demo@chemicalist.local',
      passwordHash: await hash('DemoPassw0rd!', 12),
      roles: ['admin'],
      tenantId,
    },
  });
  return tenantId;`
    : "  return undefined;"
}
  // </chemicalist:block>
}

async function main(): Promise<void> {
  const tenantId = await ensureTenantUser();

  for (const spec of models) {
    // <chemicalist:block name="scenario">
    const existing = await spec.delegate(prisma).count();
    if (existing > 0) {
      console.log(spec.name + ': ' + existing + ' rows already present, skipping');
      continue;
    }
    const seed = seedFactory(spec, tenantId);
    for (let index = 1; index <= 5; index += 1) {
      await spec.delegate(prisma).create({ data: seed(index) });
    }
    console.log(spec.name + ': created 5 demo rows');
    // </chemicalist:block>
  }
}

// <chemicalist:block name="fixtures">
function seedFactory(spec: ModelSpec, tenantId: string | undefined): (index: number) => Record<string, unknown> {
  return (index: number) => {
    const base: Record<string, unknown> = {
      id: randomUUID(),
      ...(tenantId ? { tenantId } : {}),
    };
    for (const field of spec.searchFields) {
      base[field] = 'Demo ' + field + ' #' + index;
    }
    return base;
  };
}
// </chemicalist:block>

main()
  .catch((error) => {
    console.error(error);
    process.exitCode = 1;
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
`;
}

